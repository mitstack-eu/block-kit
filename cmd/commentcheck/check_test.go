func TestCheck_AddedCommentText(t *testing.T) {
	a := goFile("a", 0, 41)
	base := map[string]string{"a/a.go": a, "b/b.go": goFile("b", 0, 5)}
	legacy := "package a\n// {MIT}-7 legacy\n" + lines(20, "var v%[1]d = %[1]d\n")
	runRows(t, []row{
		{name: "a ticket id names the file and line", base: base, head: map[string]string{"a/a.go": a + "// {MIT}-123 fixes the retry\nfunc f() {}\n"},
			code: 1, want: []string{"a/a.go:42: a comment holds a ticket id ({MIT}-123)"}},
		{name: "a file:line reference names the file and line", base: base, head: map[string]string{"a/a.go": a + "// see engine.go:412\nfunc f() {}\n"},
			code: 1, want: []string{"a/a.go:42: a comment holds a file:line reference (engine.go:412)"}},
		{name: "a comment stating a constraint passes", base: base, head: map[string]string{"a/a.go": a + "// retries once, because the API rate-limits bursts\nfunc f() {}\n"}},
		{name: "a trailing comment is judged", base: base, head: map[string]string{"a/a.go": a + "var x = 1 // {MIT}-9 note\n"},
			code: 1, want: []string{"a/a.go:42: a comment holds a ticket id ({MIT}-9)"}},
		{name: "an MS key is a ticket id", base: base, head: map[string]string{"a/a.go": a + "// {MS}-40 data model\n"},
			code: 1, want: []string{"a/a.go:42: a comment holds a ticket id ({MS}-40)"}},
		{name: "a ticket id inside an added block comment fails", base: base, head: map[string]string{"a/a.go": a + "/*\nretries for {MIT}-86\n*/\n"},
			code: 1, want: []string{"a comment holds a ticket id ({MIT}-86)"}},
		{name: "SHA-256, UTF-8 and localhost:8080 are not findings", base: base, head: map[string]string{"a/a.go": a + "// hashes SHA-256 over UTF-8 bytes from localhost:8080\n"}},
		{name: "an id and a file:line inside a Go string are not comments", base: base, head: map[string]string{"a/a.go": a + "var s = \"{MIT}-123 see engine.go:412\" // plain note\n"}},
		{name: "a committed head is judged", base: base, head: map[string]string{"a/a.go": a + "// {MIT}-123 fixes the retry\n"}, commit: true,
			code: 1, want: []string{"a/a.go:42: a comment holds a ticket id ({MIT}-123)"}},
		{name: "an untracked file is judged as wholly added", base: base, head: map[string]string{"n/new.go": "package n\n// {MIT}-5 start\n" + lines(20, "var v%[1]d = %[1]d\n")},
			code: 1, want: []string{"n/new.go:2: a comment holds a ticket id ({MIT}-5)"}},
		{name: "a TypeScript comment holding a ticket id fails", base: map[string]string{"web/a.ts": lines(20, "export const a%[1]d = %[1]d;\n")},
			head: map[string]string{"web/a.ts": lines(20, "export const a%[1]d = %[1]d;\n") + "// {MIT}-55 handles the redirect\n"},
			code: 1, want: []string{"web/a.ts:21: a comment holds a ticket id ({MIT}-55)"}},
		{name: "testdata, vendor, node_modules and generated Go are skipped", base: base, head: map[string]string{
			"a/testdata/x.go":         "// {MIT}-1 fixture\n",
			"vendor/v/v.go":           "// {MIT}-2 vendored\npackage v\n",
			"web/node_modules/m/i.ts": "// {MIT}-3 dependency\n",
			"a/gen.go":                "// Code generated by stub. DO NOT EDIT.\n\n// {MIT}-4 generated\npackage a\n",
		}},
		{name: "other file types are not judged", base: base, head: map[string]string{
			"a/x.js": "// {MIT}-6 script\n", "a/notes.md": "{MIT}-7 see engine.go:1\n", "a/run.sh": "# {MIT}-8 shell\n",
		}},
		{name: "a committed pure rename passes", base: map[string]string{"a/old.go": legacy}, mv: [][2]string{{"a/old.go", "a/new.go"}}, commit: true},
		{name: "a staged pure rename passes", base: map[string]string{"a/old.go": legacy}, mv: [][2]string{{"a/old.go", "a/new.go"}}},
		{name: "only the paths given are judged", base: base, head: map[string]string{"a/a.go": a + "// {MIT}-123 fixes the retry\n"}, args: []string{"b"}},
	})
}

func TestCheck_LexerRegressions(t *testing.T) {
	v, l, g := lines(20, "export const v%[1]d = %[1]d;\n"), lines(20, "export const l%[1]d = %[1]d;\n"), goFile("g", 0, 20)
	base := map[string]string{"web/v.tsx": v, "web/l.ts": l, "g/g.go": g}
	tsx := func(s string) map[string]string { return map[string]string{"web/v.tsx": v + s} }
	ts := func(s string) map[string]string { return map[string]string{"web/l.ts": l + s} }
	gosrc := func(s string) map[string]string { return map[string]string{"g/g.go": g + s} }
	runRows(t, []row{
		{name: "a TSX closing tag before a comment", base: base, head: tsx("export const D = () => <div>{x}</div>; // {MIT}-77 note\n"),
			code: 1, want: []string{"web/v.tsx:21: a comment holds a ticket id ({MIT}-77)"}},
		{name: "a TSX closing tag before a string holding a slash", base: base, head: tsx("export const E = () => <div>{x}</div>; const s = \"a/b // {MIT}-92\";\n")},
		{name: "a TSX self-closing tag before a comment", base: base, head: tsx("export const F = () => <Foo a={x} />; // {MIT}-78 note\n"),
			code: 1, want: []string{"web/v.tsx:21: a comment holds a ticket id ({MIT}-78)"}},
		{name: "a postfix increment before a division then a comment", base: base, head: ts("let i = 0; const y = i++ / 2 // {MIT}-79 note\n"),
			code: 1, want: []string{"web/l.ts:21: a comment holds a ticket id ({MIT}-79)"}},
		{name: "a postfix increment before a division then a string", base: base, head: ts("let j = 0; const z = j++ / 2; const q = 'a/b // {MIT}-93';\n")},
		{name: "a regex holding //", base: base, head: ts("const re = /https?:\\/\\//; const n = '{MIT}-80';\n")},
		{name: "a comment after a regex", base: base, head: ts("const re2 = /a\\/b/; // {MIT}-81 note\n"),
			code: 1, want: []string{"web/l.ts:21: a comment holds a ticket id ({MIT}-81)"}},
		{name: "a TS string holding // and /*", base: base, head: ts("const s = '// {MIT}-91 /*';\nconst t = \"{MIT}-94\";\n")},
		{name: "a TS template holding // inside ${ string }", base: base, head: ts("const u = `${ \"//\" } {MIT}-89`;\n")},
		{name: "a nested TS template holding //", base: base, head: ts("const w = `a ${ `b // {MIT}-90` } c`;\n")},
		{name: "a TS template closed after a backquote string in ${}", base: base, head: ts("const a2 = `${ \"`\" }`; // {MIT}-88 note\n"),
			code: 1, want: []string{"web/l.ts:21: a comment holds a ticket id ({MIT}-88)"}},
		{name: "a Go string holding // and /*", base: base, head: gosrc("var u = \"https://example.com/*\"\nvar k = \"{MIT}-82\"\n")},
		{name: "a Go raw string holding // and /*", base: base, head: gosrc("var r = `\n// {MIT}-83 /*\n`\nvar q = \"{MIT}-84\"\n")},
		{name: "a URL in JSX text is not a comment", base: base, head: tsx("export const P = () => <p>Docs: http://example.com/{MIT}-12</p>;\n")},
		{name: "a comment inside a JSX expression is judged", base: base, head: tsx("export const Q = () => <div>{/* {MIT}-12 */}</div>;\n"),
			code: 1, want: []string{"web/v.tsx:21: a comment holds a ticket id ({MIT}-12)"}},
		{name: "a keyword property before a division then a comment", base: base, head: ts("let x = o.in / 2 // {MIT}-3 note\n"),
			code: 1, want: []string{"web/l.ts:21: a comment holds a ticket id ({MIT}-3)"}},
		{name: "an optional keyword property before a division then a comment", base: base, head: ts("let y = o?.delete / 2 // {MIT}-4 note\n"),
			code: 1, want: []string{"web/l.ts:21: a comment holds a ticket id ({MIT}-4)"}},
	})
}

func tsFile(comments, total int) string {
	return lines(comments, "// note %d\n") + lines(total-comments, "export const v%[1]d = %[1]d;\n")
}

func TestCheck_PerFileShare(t *testing.T) {
	over, clean := goFile("p", 20, 100), goFile("p", 0, 100)
	prodFail := func(path, share string) []string {
		return []string{path + ": production comment share " + share + ", above the 7% target"}
	}
	testFail := func(path, share string) []string {
		return []string{path + ": test comment share " + share + ", above the 6% target"}
	}
	runRows(t, []row{
		{name: "a modified production file at 8% fails", base: map[string]string{"p/a.go": clean}, head: map[string]string{"p/a.go": goFile("p", 8, 100)},
			code: 1, want: prodFail("p/a.go", "8.0% (8/100)")},
		{name: "a modified production file at exactly 7% passes", base: map[string]string{"p/a.go": clean}, head: map[string]string{"p/a.go": goFile("p", 7, 100)}},
		{name: "a modified test file at 7% fails", base: map[string]string{"p/a_test.go": goFile("p", 0, 100)}, head: map[string]string{"p/a_test.go": goFile("p", 7, 100)},
			code: 1, want: testFail("p/a_test.go", "7.0% (7/100)")},
		{name: "a modified test file at exactly 6% passes", base: map[string]string{"p/a_test.go": goFile("p", 0, 100)}, head: map[string]string{"p/a_test.go": goFile("p", 6, 100)}},
		{name: "a file already over target that stays over target fails whatever it held", base: map[string]string{"p/a.go": over}, head: map[string]string{"p/a.go": goFile("p", 10, 100)},
			code: 1, want: prodFail("p/a.go", "10.0% (10/100)")},
		{name: "a file brought down to target passes", base: map[string]string{"p/a.go": over}, head: map[string]string{"p/a.go": goFile("p", 7, 100)}},
		{name: "an over-target sibling that is not touched is not judged", base: map[string]string{"p/a.go": clean, "p/b.go": over}, head: map[string]string{"p/a.go": clean + "var extra = 1\n"}},
		{name: "a newly added file over target fails", head: map[string]string{"p/n.go": goFile("p", 8, 100)},
			code: 1, want: prodFail("p/n.go", "8.0% (8/100)")},
		{name: "a deleted over-target file passes", base: map[string]string{"p/a.go": over, "p/b.go": clean}, rm: []string{"p/a.go"}},
		{name: "generated Go over target passes", head: map[string]string{"p/gen.go": "// Code generated by stub. DO NOT EDIT.\n\n" + lines(20, "// note %d\n") + "package p\n" + lines(5, "var v%[1]d = 1\n")}},
		{name: "an empty added file passes", head: map[string]string{"p/empty.go": ""}},
		{name: "a TS file under __tests__ uses the test target", base: map[string]string{"web/__tests__/x.ts": tsFile(0, 100)}, head: map[string]string{"web/__tests__/x.ts": tsFile(7, 100)},
			code: 1, want: testFail("web/__tests__/x.ts", "7.0% (7/100)")},
		{name: "a .spec.tsx file uses the test target", base: map[string]string{"web/x.spec.tsx": tsFile(0, 100)}, head: map[string]string{"web/x.spec.tsx": tsFile(7, 100)},
			code: 1, want: testFail("web/x.spec.tsx", "7.0% (7/100)")},
		{name: "a TS production file at 7% passes and at 8% fails", base: map[string]string{"web/ok.ts": tsFile(0, 100), "web/bad.ts": tsFile(0, 100)},
			head: map[string]string{"web/ok.ts": tsFile(7, 100), "web/bad.ts": tsFile(8, 100)},
			code: 1, want: prodFail("web/bad.ts", "8.0% (8/100)"), not: []string{"web/ok.ts"}},
		{name: "two failing files give two findings", base: map[string]string{"p/a.go": clean, "q/b_test.go": clean},
			head: map[string]string{"p/a.go": goFile("p", 8, 100), "q/b_test.go": goFile("q", 7, 100)},
			code: 1, want: append(prodFail("p/a.go", "8.0% (8/100)"), testFail("q/b_test.go", "7.0% (7/100)")...)},
		{name: "a file outside the paths given is not judged", base: map[string]string{"p/a.go": clean, "q/b.go": clean}, head: map[string]string{"p/a.go": goFile("p", 20, 100), "q/b.go": clean + "var extra = 1\n"}, args: []string{"q"}},
		{name: "a renamed file over target is judged at its head path", base: map[string]string{"p/old.go": clean}, mv: [][2]string{{"p/old.go", "p/new.go"}},
			head: map[string]string{"p/new.go": goFile("p", 10, 100)}, code: 1, want: prodFail("p/new.go", "10.0% (10/100)"), not: []string{"p/old.go"}},
		{name: "a pure rename of an over-target file is judged at its head path", base: map[string]string{"p/old.go": over}, mv: [][2]string{{"p/old.go", "p/new.go"}}, commit: true,
			code: 1, want: prodFail("p/new.go", "20.0% (20/100)")},
		{name: "a file at the repository root is named by its path", head: map[string]string{"root.go": goFile("root", 2, 12)},
			code: 1, want: prodFail("root.go", "16.7% (2/12)")},
		{name: "Go *p = 1 is not a comment line", base: map[string]string{"ptr/p.go": goFile("ptr", 7, 100)},
			head: map[string]string{"ptr/p.go": goFile("ptr", 7, 100) + "func f(p *int) {\n" + lines(10, "\t*p = %d\n") + "}\n"}},
		{name: "a line ending in a comment is not a comment line", base: map[string]string{"tr/t.go": goFile("tr", 7, 100)},
			head: map[string]string{"tr/t.go": goFile("tr", 7, 100) + lines(10, "var w%[1]d = 1 // note %[1]d\n")}},
		{name: "block comment continuation lines count", base: map[string]string{"blk/b.go": goFile("blk", 4, 100)},
			head: map[string]string{"blk/b.go": goFile("blk", 4, 100) + "/*\nalpha\nbeta\ngamma\n*/\n"},
			code: 1, want: prodFail("blk/b.go", "8.6% (9/105)")},
	})
}

func TestCheck_PerFileFindingsSortByPath(t *testing.T) {
	dir, base := repoAt(t, map[string]string{"z/z.go": goFile("z", 0, 100), "a/a.go": goFile("a", 0, 100)})
	write(t, dir, map[string]string{"z/z.go": goFile("z", 8, 100), "a/a.go": goFile("a", 9, 100)})

	out, _, code := run("-repo", dir, "-base", base)

	first, second := strings.Index(out, "a/a.go: production"), strings.Index(out, "z/z.go: production")
	if code != 1 || first < 0 || second < first {
		t.Errorf("exit %d; want 1 with a/a.go before z/z.go; stdout:\n%s", code, out)
	}
}
