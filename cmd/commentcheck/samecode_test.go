package main

import "testing"

func TestSameCode(t *testing.T) {
	goA := "//go:build linux\n\n// Package a does a thing.\npackage a\n\n// f returns one.\nfunc f() int { return 1 } // trailing\n"
	tsS := "export const a = 1; // trailing\n/* block */ export const b = 2;\n// tail\n"
	sc := []string{"-same-code"}
	runRows(t, []row{
		{name: "deleting only Go comments passes", base: map[string]string{"a/a.go": goA}, args: sc,
			head: map[string]string{"a/a.go": "//go:build linux\n\npackage a\n\nfunc f() int { return 1 }\n"}},
		{name: "a changed Go statement fails naming the file", base: map[string]string{"a/a.go": goA}, args: sc,
			head: map[string]string{"a/a.go": "//go:build linux\n\npackage a\n\nfunc f() int { return 2 }\n"},
			code: 1, want: []string{"a/a.go: code differs from {base}"}},
		{name: "removing a go:build directive fails", base: map[string]string{"a/a.go": goA}, args: sc,
			head: map[string]string{"a/a.go": "// Package a does a thing.\npackage a\n\n// f returns one.\nfunc f() int { return 1 } // trailing\n"},
			code: 1, want: []string{"a/a.go: code differs from {base}"}},
		{name: "deleting a doc-only Go file passes", base: map[string]string{"a/a.go": goA, "a/doc.go": "// Package a does a thing.\npackage a\n"}, rm: []string{"a/doc.go"}, args: sc},
		{name: "deleting a Go file with code fails", base: map[string]string{"a/a.go": goA}, rm: []string{"a/a.go"}, args: sc,
			code: 1, want: []string{"a/a.go: code differs from {base}"}},
		{name: "a rename is a delete plus an add", base: map[string]string{"a/a.go": goA}, mv: [][2]string{{"a/a.go", "a/b.go"}}, commit: true, args: sc,
			code: 1, want: []string{"a/b.go: code differs from {base}"}},
		{name: "an explicit and an automatic semicolon compare equal", base: map[string]string{"a/a.go": "package a\n\nvar x = 1; // one\n"}, args: sc,
			head: map[string]string{"a/a.go": "package a\n\nvar x = 1\n"}},
		{name: "a changed cgo preamble fails", base: map[string]string{"a/a.go": "package a\n\n// #include <stdio.h>\nimport \"C\"\n"}, args: sc,
			head: map[string]string{"a/a.go": "package a\n\n// #include <stdlib.h>\nimport \"C\"\n"},
			code: 1, want: []string{"a/a.go: code differs from {base}"}},
		{name: "a Go file that fails to scan never passes", base: map[string]string{"a/a.go": "package a\n\n// note\nvar s = \"abc\n"}, args: sc,
			head: map[string]string{"a/a.go": "package a\n\nvar s = \"abc\n"},
			code: 1, want: []string{"a/a.go: code differs from {base}"}},
		{name: "deleting only TS comments passes", base: map[string]string{"web/s.ts": tsS}, args: sc,
			head: map[string]string{"web/s.ts": "export const a = 1;\nexport const b = 2;\n"}},
		{name: "a changed TS statement fails naming the file", base: map[string]string{"web/s.ts": tsS}, args: sc,
			head: map[string]string{"web/s.ts": "export const a = 1;\nexport const b = 3;\n"},
			code: 1, want: []string{"web/s.ts: code differs from {base}"}},
		{name: "a line break inside a removed TS comment matters", base: map[string]string{"web/r.ts": "export function f() {\n  return /*\n  */ 1;\n}\n"}, args: sc,
			head: map[string]string{"web/r.ts": "export function f() {\n  return 1;\n}\n"},
			code: 1, want: []string{"web/r.ts: code differs from {base}"}},
		{name: "deleting a TSX trailing comment passes", base: map[string]string{"web/v.tsx": "export const V = () => <div>{x}</div>; // note\n"}, args: sc,
			head: map[string]string{"web/v.tsx": "export const V = () => <div>{x}</div>;\n"}},
		{name: "an added TS file holding only comments passes", args: sc, head: map[string]string{"web/n.ts": "// placeholder\n/* nothing yet */\n"}},
		{name: "other file types are not judged", base: map[string]string{"a/a.go": goA, "notes.md": "old\n", "a/x.js": "var a = 1;\n"}, args: sc,
			head: map[string]string{"a/a.go": "//go:build linux\n\npackage a\n\nfunc f() int { return 1 }\n", "notes.md": "new\n", "a/x.js": "var a = 2;\n"},
			not:  []string{"notes.md", "x.js"}},
		{name: "testdata and generated Go are skipped", args: sc, head: map[string]string{
			"a/testdata/t.go": "package t\nvar x = 1\n",
			"a/gen.go":        "// Code generated by stub. DO NOT EDIT.\n\npackage a\nvar g = 1\n",
		}},
		{name: "a changed URL in JSX text fails", base: map[string]string{"web/v.tsx": "export const L = () => <a href={u}>https://old.example.com</a>;\n"}, args: sc,
			head: map[string]string{"web/v.tsx": "export const L = () => <a href={u}>https://new.example.com</a>;\n"},
			code: 1, want: []string{"web/v.tsx: code differs from {base}"}},
		{name: "a /* in JSX text opens no comment", base: map[string]string{"web/c.tsx": "export const C = () => <code>/*</code>;\nexport let n = 1;\nexport const k = 4; // */\n"}, args: sc,
			head: map[string]string{"web/c.tsx": "export const C = () => <code>/*</code>;\nexport let n = 2;\nexport const k = 4; // */\n"},
			code: 1, want: []string{"web/c.tsx: code differs from {base}"}},
		{name: "a slash opening a line after a closing brace starts a regex", base: map[string]string{"web/g.ts": tsRegexLine("run(1)")}, args: sc,
			head: map[string]string{"web/g.ts": tsRegexLine("run(2)")},
			code: 1, want: []string{"web/g.ts: code differs from {base}"}},
		{name: "a changed Example output fails", base: map[string]string{"a/a_test.go": example("// Output: 1")}, args: sc,
			head: map[string]string{"a/a_test.go": example("// Output: 2")},
			code: 1, want: []string{"a/a_test.go: code differs from {base}"}},
		{name: "a changed Example unordered output fails", base: map[string]string{"a/a_test.go": example("// Unordered output: a")}, args: sc,
			head: map[string]string{"a/a_test.go": example("// Unordered output: b")},
			code: 1, want: []string{"a/a_test.go: code differs from {base}"}},
		{name: "a changed line under a bare Example output fails", base: map[string]string{"a/a_test.go": example("// Output:\n\t// 1")}, args: sc,
			head: map[string]string{"a/a_test.go": example("// Output:\n\t// 2")},
			code: 1, want: []string{"a/a_test.go: code differs from {base}"}},
		{name: "deleting an ordinary comment in an Example passes", base: map[string]string{"a/a_test.go": example("// prints one\n\t// Output: 1")}, args: sc,
			head: map[string]string{"a/a_test.go": example("// Output: 1")}},
	})
}

func tsRegexLine(call string) string {
	return "export function f(s: string) {\n  if (s) {\n    run(0);\n  }\n/\\/\\//.test(s) && " + call + ";\n}\n"
}

func example(output string) string {
	return "package a\n\nimport \"fmt\"\n\nfunc ExampleF() {\n\tfmt.Println(1)\n\t" + output + "\n}\n"
}
